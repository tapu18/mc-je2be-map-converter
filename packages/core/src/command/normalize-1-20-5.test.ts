import { expect, it } from "vitest";
import { normalize1_20_5ItemsAndText } from "./normalize-1-20-5.ts";
import { normalizeCommandIR } from "./normalize-command.ts";
import { CommandParser, toCommandIR, type CommandIR, type CommandTreeNode, type ParsedNode } from "./parser.ts";

const literal = (children: Record<string, CommandTreeNode>): CommandTreeNode => ({ type: "literal", children });
const arg = (parser: string, children?: Record<string, CommandTreeNode>): CommandTreeNode =>
  children ? { type: "argument", parser, children } : { type: "argument", parser, executable: true };
const path = arg("minecraft:nbt_path");
const entityPath = { target: arg("minecraft:entity", { path }) };
// The relevant branches of the commands.json generated by both releases use the same parser IDs.
const tree: CommandTreeNode = { type: "root", children: {
  give: literal({ targets: arg("minecraft:entity", { item: arg("minecraft:item_stack") }) }),
  clear: literal({ targets: arg("minecraft:entity", { item: arg("minecraft:item_predicate") }) }),
  data: literal({
    get: literal({
      block: literal({ targetPos: arg("minecraft:block_pos", { path }) }),
      entity: literal(entityPath),
      storage: literal({ target: arg("minecraft:resource_location", { path }) }),
    }),
    remove: literal({ entity: literal(entityPath) }),
  }),
  execute: literal({
    if: literal({ data: literal({ entity: literal({
      source: arg("minecraft:entity", { path: { ...path, redirect: ["execute"] } }),
    }) }) }),
    run: { type: "literal" },
  }),
  return: literal({ run: { type: "literal" } }),
  tellraw: literal({ targets: arg("minecraft:entity", { message: arg("minecraft:component") }) }),
} };
const old = new CommandParser(tree, { version: "1.20.4", textFormat: "json" });
const next = new CommandParser(tree, { version: "1.20.5", textFormat: "json" });

function parse(parser: CommandParser, source: string): CommandIR {
  const result = parser.parse(source);
  if (!result.ok) throw new Error(JSON.stringify(result.error));
  return toCommandIR(source, result.nodes);
}

function withoutSourcePositions(ir: CommandIR): unknown {
  const nodes = (entries: ParsedNode[]) => entries.map(({ start: _start, end: _end, ...node }) => node);
  const command = ir.command;
  return {
    context: ir.context.map(step => ({ ...step, nodes: nodes(step.nodes) })),
    command: command && { name: command.name, nodes: nodes(command.nodes), run: command.run && withoutSourcePositions(command.run) },
  };
}

const oldText = String.raw`tellraw @a ["Example",{"text":"item","hoverEvent":{"action":"show_item","contents":{"id":"stone","count":2,"tag":"{foo:1b}"}}}]`;
const newText = 'tellraw @a ["Example",{"text":"item","hoverEvent":{"action":"show_item","contents":{"id":"stone","count":2,"components":{"minecraft:custom_data":{"foo":true}}}}}]';

it.each([
  ['give @s stick{foo:"test",num:1b}', 'give @s stick[custom_data={foo:"test",num:1b}]'],
  ["clear @s #minecraft:logs{foo:1b}", "clear @s #minecraft:logs[custom_data~{foo:1b}]"],
  ["data get entity @s SelectedItem.tag.foo", 'data get entity @s SelectedItem.components."minecraft:custom_data".foo'],
  ["data get block 0 0 0 Items[{Slot:0b}].tag.foo", 'data get block 0 0 0 Items[{Slot:0b}].components."minecraft:custom_data".foo'],
  ["execute if data entity @s HandItems[0].tag.foo run return run " + oldText,
    'execute if data entity @s HandItems[0].components."minecraft:custom_data".foo run return run ' + newText],
  [oldText, newText],
])("normalizes %s to the 1.20.5 IR", (before, after) => {
  const original = parse(old, before);
  const result = normalize1_20_5ItemsAndText(original);
  expect(result.ok).toBe(true);
  if (!result.ok) throw new Error(result.reason);
  expect(result.ir.source).toBe(before);
  const expected = parse(next, after);
  expect(withoutSourcePositions(result.ir)).toEqual(withoutSourcePositions(expected));
  const composed = normalizeCommandIR(original, "1.20.4");
  const current = normalizeCommandIR(expected, "1.20.5");
  expect(composed.ok && current.ok).toBe(true);
  if (composed.ok && current.ok) expect(withoutSourcePositions(composed.ir)).toEqual(withoutSourcePositions(current.ir));
});

it.each([
  ["return run give @s stone{HideFlags:1}", "stone{HideFlags:1}", "専用コンポーネント"],
  ["clear @s stone{}", "stone{}", "空の旧アイテム tag"],
  ["data get entity @s SelectedItem.tag", "SelectedItem.tag", "tag 全体"],
  ["data get entity @s Inventory[{tag:{foo:1b}}].id", "Inventory[{tag:{foo:1b}}].id", "フィルタ"],
  ["data remove entity @s SelectedItem.tag.foo", "SelectedItem.tag.foo", "書き込み・削除"],
  [oldText.replace("foo:1b", "foo:[I;1,2]"), oldText.slice("tellraw @a ".length).replace("foo:1b", "foo:[I;1,2]"), "NBT 型"],
  [oldText.replace("foo:1b", "foo:"), oldText.slice("tellraw @a ".length).replace("foo:1b", "foo:"), "解析できない"],
  ['tellraw @a {"nbt":"SelectedItem.tag.foo","entity":"@s"}', '{"nbt":"SelectedItem.tag.foo","entity":"@s"}', "旧アイテム tag 参照"],
])("diagnoses %s at its original argument", (before, argument, reason) => {
  const source = "/" + before;
  const start = source.indexOf(argument);
  expect(normalizeCommandIR(parse(old, source), "1.20.4")).toEqual({
    ok: false, reason: expect.stringContaining("1.20.4 → 1.20.5: "), start, end: start + argument.length,
  });
  expect(normalizeCommandIR(parse(old, source), "1.20.4")).toMatchObject({ reason: expect.stringContaining(reason) });
});

it("keeps storage keys and ordinary JSON unchanged and reads item syntax in its original version", () => {
  for (const command of ["data get storage test:data Item.tag.foo", String.raw`tellraw @a {"text":"日本語\/text","bold":true}`]) {
    const ir = parse(old, command);
    expect(normalizeCommandIR(ir, "1.20.4")).toEqual({ ok: true, ir });
  }
  expect(next.parse("give @s stone{foo:1b}").ok).toBe(false);
  expect(old.parse("give @s stone[custom_data={foo:1b}]").ok).toBe(false);
  expect(old.parse("clear @s *").ok).toBe(false);
  expect(next.parse("clear @s *").ok).toBe(true);
});
