describe("コマンドパーサと Java 版サーバーの判定", () => {
  let java: JavaSyntaxResult[];
  let parser: CommandParser;
  beforeAll(async () => {
    const tree = JSON.parse(readFileSync(join(paths.blocksReport, "..", "commands.json"), "utf8")) as CommandTreeNode;
    parser = new CommandParser(tree, { textFormat: "snbt" });
    java = await checkJavaSyntax(CASES.map(([c]) => c));
  }, 240_000);

  it("Java の判定が記録と一致する", () => {
    const actual = java.map((j, i) => [j.command, j.ok ? "ok" : CASES[i]?.[1] === "semantic" ? "semantic" : "ng"]);
    expect(actual).toEqual(CASES);
  });

  it("パーサの判定が Java と一致する（semantic はパーサだけが読める）", () => {
    const actual = CASES.map(([c, v]) => [c, parser.parse(c).ok ? (v === "semantic" ? "semantic" : "ok") : "ng"]);
    expect(actual).toEqual(CASES);
  });
});
